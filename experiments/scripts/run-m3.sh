#!/bin/bash
# M3 run matrix: baseline / plugin-hot / plugin-cold / plugin-auto.
# Each run uses the isolated experiment DSH_HOME (20K window) and the same task text.
#
# Mechanism (fixed 2026-08-15, two rounds of实测):
# - dsh-base ALREADY composes the full compaction stack at the root realm:
#   compaction-basic + command-compact + stock tool-result-pruner. The
#   settings.yaml `agent-presets.default` switch is inert for headless (no
#   agent-presets service), and inserting an isolate group deadlocks
#   command-compact ("waiting for service: compaction").
# - baseline: EMPTY patch = pure stock dsh behavior (compaction-basic, stock
#   pruner). plugin-*: disable the compaction-basic row and insert the
#   cache-aware engine at the root realm (headless = single-session process,
#   root sharing is safe). The pruner stays stock in ALL variants (fairness).
# - Verified: plugin row load + schema validation via negative mount test
#   (bogus coldMode -> loader schema error, exit 1).
#
# Usage: ./run-m3.sh baseline|plugin-hot|plugin-cold|plugin-auto|plugin-cold-refuse
set -euo pipefail

ROOT="${ROOT:-$(cd "$(dirname "$0")/.." && pwd)}"
HOME_DIR="$ROOT/dsh-home"
PATCH="$HOME_DIR/profiles/headless/cordis.patch.yml"
TASK="$(node --input-type=module -e "import('$ROOT/scripts/task.js').then(m => process.stdout.write(m.M3_TASK))")"

# API key comes from experiments/.env (gitignored, chmod 600); never from chat.
ENV_FILE="$ROOT/.env"
if [ -f "$ENV_FILE" ]; then
  set -a; . "$ENV_FILE"; set +a
else
  echo "error: missing $ENV_FILE (expects OPENCODE_GO_API_KEY=...); create it first" >&2
  exit 3
fi

variant="${1:?usage: run-m3.sh baseline|plugin-hot|plugin-cold|plugin-auto|plugin-cold-refuse}"

# Write the headless patch layer for this variant.
python3 - "$PATCH" "$variant" <<'EOF'
import sys
p, variant = sys.argv[1], sys.argv[2]
if variant == "baseline":
    patch = "# Generated by run-m3.sh (baseline) - stock dsh compaction stack.\n[]\n"
else:
    # Explicit variant -> (coldMode, cachePolicy) mapping. A naive
    # `variant.replace("plugin-", "")` would turn "plugin-cold-refuse" into the
    # invalid cachePolicy "cold-refuse" and fail loader schema validation.
    variant_config = {
        "plugin-hot": ("transcribe", "hot"),
        "plugin-cold": ("transcribe", "cold"),
        "plugin-auto": ("transcribe", "auto"),
        "plugin-cold-refuse": ("refuse", "cold"),
    }
    cold_mode, policy = variant_config[variant]
    patch = (
        f"# Generated by run-m3.sh ({variant}) - do not hand-edit.\n"
        "- id: compaction-basic\n"
        "  disabled: true\n"
        "- insert:\n"
        "    - id: compaction-cache-aware\n"
        "      name: '@septtpes/dsh-compaction-cache-aware'\n"
        "      config:\n"
        f"        coldMode: {cold_mode}\n"
        f"        cachePolicy: {policy}\n"
    )
open(p, "w").write(patch)
print(f"patch written for {variant}")
EOF

# Reset the task repo to pristine before each run: the task mutates src/sum.js,
# creates test/run.js and dump files; without this the variants are not comparable.
# (Agent cwd is $ROOT/tasks, so dumps land BOTH in ./repo and in ./ itself.)
git -C "$(dirname "$ROOT")" checkout -- experiments/tasks/repo
rm -rf "$ROOT/tasks/repo/test" "$ROOT/tasks/repo/dump1.txt" "$ROOT/tasks/repo/dump2.txt" "$ROOT/tasks/repo/dump3.txt" "$ROOT/tasks/repo/dump4.txt" "$ROOT/tasks/repo/dump5.txt" "$ROOT/tasks/repo/dump6.txt" "$ROOT/tasks/repo/result.txt"
rm -f "$ROOT/tasks/dump1.txt" "$ROOT/tasks/dump2.txt" "$ROOT/tasks/dump3.txt" "$ROOT/tasks/dump4.txt" "$ROOT/tasks/dump5.txt" "$ROOT/tasks/dump6.txt" "$ROOT/tasks/result.txt"

cd "$ROOT/tasks"
echo "=== run: $variant ==="
# DSH_PERMISSION_MODE=danger-full-access: this host's macOS sandbox-exec backend
# fails (sandbox_apply) for workspace-write, which blocks the agent's bash tool
# (observed 2026-08-15). The env override is the dsh-base sanctioned switch
# (sandbox-policy row reads it); scoped to the isolated experiment home only.
DSH_HOME="$HOME_DIR" DSH_PERMISSION_MODE=danger-full-access dsh --profile headless "$TASK" 2>&1 | tail -5
echo "dsh exit: ${PIPESTATUS[0]:-0}"

# Newest session in the experiment home.
SESSION="$(find "$HOME_DIR/sessions" -name 'session.jsonl.zstd' -newer "$PATCH" -print0 2>/dev/null | xargs -0 ls -t 2>/dev/null | head -1)"
if [ -z "$SESSION" ]; then
  SESSION="$(find "$HOME_DIR/sessions" -name 'session.jsonl.zstd' -print0 | xargs -0 ls -t | head -1)"
fi
echo "=== session: $SESSION ==="
python3 "$ROOT/scripts/extract.py" "$SESSION"
echo "$SESSION" > "$ROOT/tasks/.last-session-$variant"
